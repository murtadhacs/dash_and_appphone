/// بيانات النموذج بعد التحقق منها.
class StudentInput {
  final String name;
  final String parentName;

  /// بالصيغة القياسية `+9647XXXXXXXXX`.
  final String parentPhone;

  /// كلمة مرور وفق القاعدة الجديدة، وإلا null للإبقاء على الحالية.
  final String? parentPin;
  final String? rfidTag;
  final String? grade;
  final String? section;

  const StudentInput({
    required this.name,
    required this.parentName,
    required this.parentPhone,
    this.parentPin,
    this.rfidTag,
    this.grade,
    this.section,
  });
}

const _none = '';

const _presetGrades = [
  'روضة 1',
  'روضة 2',
  'تمهيدي',
  'الصف الأول الابتدائي',
  'الصف الثاني الابتدائي',
  'الصف الثالث الابتدائي',
  'الصف الرابع الابتدائي',
  'الصف الخامس الابتدائي',
  'الصف السادس الابتدائي',
];

const _presetSections = ['شعبة أ', 'شعبة ب', 'شعبة ج', 'شعبة د'];

/// نافذة إضافة / تعديل طالب.
///
/// [knownParentPhones] أرقام أولياء الأمور المسجّلين (من قائمة الطلاب): لرقم جديد
/// تُولَّد كلمة مرور لولي أمر جديد، وتبقى اختيارية للرقم المسجّل.
///
/// [onSubmit] تنفّذ الطلب فعلياً؛ إن رمت [ApiException] تبقى النافذة مفتوحة
/// مع عرض الرسالة، وإلا تُغلق وتُرجع [StudentInput] المحفوظ (أو null عند الإلغاء).
class StudentFormDialog extends StatefulWidget {
  final Student? editing;
  final Set<String> knownParentPhones;
  final List<Student> knownStudents;

  /// الصفوف والشعب الموجودة فعلاً في بيانات الطلاب (تُستخدم كخيارات، وإلا القوائم الافتراضية).
  final List<String> knownGrades;
  final List<String> knownSections;
  final Future<void> Function(StudentInput input) onSubmit;

  const StudentFormDialog({
    super.key,
    this.editing,
    required this.knownParentPhones,
    this.knownStudents = const [],
    this.knownGrades = const [],
    this.knownSections = const [],
    required this.onSubmit,
  });

  static Future<StudentInput?> show(
    BuildContext context, {
    Student? editing,
    required Set<String> knownParentPhones,
    List<Student> knownStudents = const [],
    List<String> knownGrades = const [],
    List<String> knownSections = const [],
    required Future<void> Function(StudentInput input) onSubmit,
  }) {
    return showDialog<StudentInput>(
      context: context,
      barrierDismissible: false,
      builder: (_) => StudentFormDialog(
        editing: editing,
        knownParentPhones: knownParentPhones,
        knownStudents: knownStudents,
        knownGrades: knownGrades,
        knownSections: knownSections,
        onSubmit: onSubmit,
      ),
    );
  }

  @override
  State<StudentFormDialog> createState() => _StudentFormDialogState();
}

class _StudentFormDialogState extends State<StudentFormDialog> {
  final _formKey = GlobalKey<FormState>();

  late final _name = TextEditingController(text: widget.editing?.name ?? '');
  late final _parentName = TextEditingController(
    text: widget.editing?.parentName ?? '',
  );
  late final _phone = TextEditingController(
    text: widget.editing == null || widget.editing!.parentPhone.isEmpty
        ? ''
        : IraqiPhone.display(widget.editing!.parentPhone),
  );
  late final _rfid = TextEditingController(text: widget.editing?.rfidTag ?? '');
  final _pin = TextEditingController();

  late String _grade = widget.editing?.grade ?? _none;
  late String _section = widget.editing?.section ?? _none;
  bool _showPin = false;
  bool _pinAutoGenerated = false;
  bool _saving = false;
  String? _error;
  String? _rfidError, _suggestedRfid;
  String? _requiresPinPhone;

  bool get _isEdit => widget.editing != null;

  /// الرقم الحالي بعد التطبيع، أو null إن لم يكتمل/لم يصح.
  String? get _normalizedPhone => IraqiPhone.normalize(_phone.text);

  /// ولي أمر جديد: رقم صالح غير موجود بين الأولياء المسجّلين.
  bool get _isNewParent {
    final p = _normalizedPhone;
    if (p == null) return !_isEdit;
    return p == _requiresPinPhone ||
        !widget.knownParentPhones.any(
          (phone) => IraqiPhone.normalize(phone) == p,
        );
  }

  @override
  void initState() {
    super.initState();
    _syncPin();
  }

  @override
  void dispose() {
    for (final c in [_name, _parentName, _phone, _rfid, _pin]) {
      c.dispose();
    }
    super.dispose();
  }

  /// يولّد رمزاً لولي أمر جديد، ويمسح الرمز المولَّد تلقائياً إذا صار الرقم لولي أمر مسجّل.
  void _syncPin() {
    if (_isNewParent) {
      if (_pin.text.isEmpty) {
        _pin.text = generateParentPin();
        _pinAutoGenerated = true;
      }
    } else if (!_isEdit || _pinAutoGenerated) {
      _pin.clear();
      _pinAutoGenerated = false;
    }
    if (!_isEdit && !_isNewParent) {
      final parent = widget.knownStudents
          .where((s) => IraqiPhone.normalize(s.parentPhone) == _normalizedPhone)
          .firstOrNull;
      if (parent != null) _parentName.text = parent.parentName;
    }
  }

  Future<void> _chooseParent() async {
    final parents = <String, Student>{};
    for (final student in widget.knownStudents) {
      final phone = IraqiPhone.normalize(student.parentPhone);
      if (phone != null) parents.putIfAbsent(phone, () => student);
    }
    String query = '';
    final selected = await showDialog<Student>(
      context: context,
      builder: (ctx) => StatefulBuilder(
        builder: (ctx, update) => AppDialog(
          title: 'اختيار ولي أمر مسجّل',
          icon: LucideIcons.usersRound,
          subtitle: 'ابحث باسم ولي الأمر أو أحد أبنائه أو رقم الهاتف',
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              AppTextField(
                hint: 'اسم ولي الأمر، الابن أو رقم الهاتف',
                prefixIcon: LucideIcons.search,
                onChanged: (value) =>
                    update(() => query = value.trim().toLowerCase()),
              ),
              const SizedBox(height: 12),
              SizedBox(
                height: 280,
                child: ListView(
                  children: [
                    for (final entry in parents.entries)
                      if (widget.knownStudents.any(
                        (s) =>
                            IraqiPhone.normalize(s.parentPhone) == entry.key &&
                            '${s.parentName} ${s.parentPhone} ${IraqiPhone.display(s.parentPhone)} ${s.name}'
                                .toLowerCase()
                                .contains(query),
                      ))
                        ListTile(
                          title: Text(entry.value.parentName),
                          subtitle: Text(
                            '${IraqiPhone.display(entry.key)} • ${widget.knownStudents.where((s) => IraqiPhone.normalize(s.parentPhone) == entry.key).map((s) => s.name).join('، ')}',
                          ),
                          trailing: const Icon(LucideIcons.chevronLeft),
                          onTap: () => Navigator.pop(ctx, entry.value),
                        ),
                    if (parents.isEmpty)
                      const ListTile(
                        title: Text('لا يوجد أولياء أمور مسجّلون بعد'),
                      ),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
    if (selected != null && mounted) {
      setState(() {
        _phone.text = IraqiPhone.display(selected.parentPhone);
        _parentName.text = selected.parentName;
        _syncPin();
      });
    }
  }

  List<DropdownItem<String>> _items(List<String> presets, String current) {
    final all = [
      ...presets,
      if (current.isNotEmpty && !presets.contains(current)) current,
    ];
    return [
      const DropdownItem(_none, 'غير محدد'),
      for (final v in all) DropdownItem(v, v),
    ];
  }

  Future<void> _copyPin() async {
    await Clipboard.setData(ClipboardData(text: _pin.text));
    if (mounted) showAppToast(context, 'تم نسخ كلمة المرور');
  }

  Future<void> _submit() async {
    if (_saving || !_formKey.currentState!.validate()) return;

    final input = StudentInput(
      name: _name.text.trim(),
      parentName: _parentName.text.trim(),
      parentPhone: _normalizedPhone!,
      parentPin: (!_isEdit && !_isNewParent) || _pin.text.isEmpty
          ? null
          : _pin.text,
      rfidTag: _rfid.text.trim().isEmpty ? null : _rfid.text.trim(),
      grade: _grade.isEmpty ? null : _grade,
      section: _section.isEmpty ? null : _section,
    );

    setState(() {
      _saving = true;
      _error = null;
      _rfidError = null;
      _suggestedRfid = null;
    });
    try {
      await widget.onSubmit(input);
      if (mounted) Navigator.of(context).pop(input);
    } on ApiException catch (e) {
      if (!mounted) return;
      setState(() {
        _saving = false;
        if (e.statusCode == 409) {
          _suggestedRfid = e.suggestedRfidTag;
          _rfidError =
              'الرقم ${input.rfidTag ?? _rfid.text} مسجل لطالب آخر'
              '${_suggestedRfid == null ? '' : '، يمكنك استخدام $_suggestedRfid'}';
        } else if (e.statusCode == 400 &&
            (e.serverMessage ?? '').contains('rfid_tag')) {
          _rfidError = e.serverMessage ?? e.message;
        } else {
          if (e.statusCode == 400 &&
              (e.serverMessage ?? '').startsWith('parent_pin is required')) {
            _requiresPinPhone = input.parentPhone;
            _syncPin();
          }
          _error = e.studentSaveMessage;
        }
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final knownParent = !_isEdit && !_isNewParent && _normalizedPhone != null;
    return AppDialog(
      icon: _isEdit ? LucideIcons.pencil : LucideIcons.userPlus,
      title: _isEdit ? 'تعديل بيانات الطالب' : 'إضافة طالب جديد',
      subtitle: 'أدخل بيانات الطالب وولي أمره',
      maxWidth: 600,
      onClose: _saving ? () {} : null,
      child: Form(
        key: _formKey,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            if (_error != null) _errorBanner(),
            _labeled(
              const FieldLabel('اسم الطالب', required: true),
              AppTextField(
                controller: _name,
                hint: 'مثال: ريان فهد الحارثي',
                maxLength: 100,
                requiredField: true,
              ),
            ),
            const SizedBox(height: 16),
            _labeled(
              const FieldLabel(
                'معرّف RFID',
                required: true,
                hint: 'رقم المستخدم في جهاز البصمة',
              ),
              AppTextField(
                controller: _rfid,
                ltr: true,
                mono: true,
                maxLength: _isEdit ? 50 : 14,
                keyboardType: TextInputType.number,
                formatters: _isEdit
                    ? null
                    : [
                        TextInputFormatter.withFunction(
                          (oldValue, newValue) =>
                              RegExp(r'^[0-9]*$').hasMatch(newValue.text)
                              ? newValue
                              : oldValue,
                        ),
                      ],
                validator: (v) {
                  final value = (v ?? '').trim();
                  if (_isEdit &&
                      value.isNotEmpty &&
                      value == widget.editing!.rfidTag) {
                    return null;
                  }
                  if (value.isEmpty) return 'رقم المستخدم في جهاز البصمة مطلوب';
                  return RegExp(r'^[1-9][0-9]{0,13}$').hasMatch(value)
                      ? null
                      : 'استخدم أرقاماً لاتينية فقط: 1 إلى 14 خانة، دون صفر في البداية';
                },
                onChanged: (_) => setState(() {
                  _rfidError = null;
                  _suggestedRfid = null;
                }),
                hint: _isEdit
                    ? 'رقم المستخدم المسجّل على الجهاز'
                    : 'مثال: 1001',
              ),
              help:
                  'يجب أن يطابق رقم المستخدم المسجّل للطالب في جهاز البصمة تماماً.',
            ),
            if (_rfidError != null)
              Padding(
                padding: const EdgeInsets.only(top: 6),
                child: Text(
                  _rfidError!,
                  style: const TextStyle(
                    color: AppColors.redDark,
                    fontSize: 12,
                  ),
                ),
              ),
            if (_suggestedRfid != null) ...[
              Align(
                alignment: AlignmentDirectional.centerStart,
                child: Padding(
                  padding: const EdgeInsets.only(top: 6),
                  child: AppButton(
                    label: 'استخدام الرقم $_suggestedRfid',
                    icon: LucideIcons.wandSparkles,
                    style: AppButtonStyle.outline,
                    small: true,
                    onPressed: _saving
                        ? null
                        : () => setState(() {
                            _rfid.text = _suggestedRfid!;
                            _rfidError = null;
                            _suggestedRfid = null;
                          }),
                  ),
                ),
              ),
              const SizedBox(height: 4),
              const Text(
                'الاقتراح غير محجوز؛ تأكد من مطابقة الرقم على جهاز البصمة.',
                style: TextStyle(fontSize: 11, color: AppColors.textMuted),
              ),
            ],
            const SizedBox(height: 16),
            _twoCols(
              _labeled(
                const FieldLabel('الصف'),
                AppDropdown<String>(
                  value: _grade,
                  items: _items(
                    widget.knownGrades.isEmpty
                        ? _presetGrades
                        : widget.knownGrades,
                    _grade,
                  ),
                  onChanged: (v) => setState(() => _grade = v),
                ),
              ),
              _labeled(
                const FieldLabel('الشعبة'),
                AppDropdown<String>(
                  value: _section,
                  items: _items(
                    widget.knownSections.isEmpty
                        ? _presetSections
                        : widget.knownSections,
                    _section,
                  ),
                  onChanged: (v) => setState(() => _section = v),
                ),
              ),
            ),
            const SizedBox(height: 16),
            if (!_isEdit) ...[
              Row(
                children: [
                  AppButton(
                    label: 'اختيار ولي أمر مسجّل',
                    icon: LucideIcons.usersRound,
                    style: AppButtonStyle.outline,
                    small: true,
                    onPressed: _saving ? null : _chooseParent,
                  ),
                  const SizedBox(width: 10),
                  const Expanded(
                    child: Text(
                      'لإضافة أخ أو أخت لطالب مسجّل، اختر ولي أمره لربط الأبناء بالحساب نفسه.',
                      style: TextStyle(
                        fontSize: 12,
                        color: AppColors.textMuted,
                      ),
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 12),
            ],
            if (_isEdit && widget.editing!.parentPhone.isEmpty) ...[
              const DialogNote(
                'لا يوجد ولي أمر مرتبط بهذا الطالب. أدخل بيانات ولي الأمر كاملة؛ حفظ التعديلات يعيد ربط الطالب بالرقم.',
                tone: NoteTone.warn,
              ),
              const SizedBox(height: 12),
            ],
            _twoCols(
              _labeled(
                const FieldLabel('اسم ولي الأمر', required: true),
                AppTextField(
                  controller: _parentName,
                  hint: 'مثال: فهد عبد الله الحارثي',
                  maxLength: 255,
                  requiredField: true,
                ),
              ),
              _labeled(
                const FieldLabel('رقم هاتف ولي الأمر', required: true),
                AppTextField(
                  controller: _phone,
                  hint: '07XXXXXXXXX',
                  ltr: true,
                  keyboardType: TextInputType.phone,
                  onChanged: (_) => setState(_syncPin),
                  validator: (v) {
                    if (v == null || v.trim().isEmpty) {
                      return 'هذا الحقل مطلوب';
                    }
                    return IraqiPhone.normalize(v) == null
                        ? 'أدخل رقماً عراقياً صحيحاً مثل 07701234567'
                        : null;
                  },
                ),
              ),
            ),
            const SizedBox(height: 16),
            if (knownParent)
              DialogNote(
                'سيُربط الطالب بحساب ولي الأمر المسجّل\n'
                'يستخدم ولي الأمر كلمة مروره الحالية للوصول إلى جميع أبنائه.'
                '${widget.knownStudents.any((s) => IraqiPhone.normalize(s.parentPhone) == _normalizedPhone) ? '\nالأبناء المسجّلون: ${widget.knownStudents.where((s) => IraqiPhone.normalize(s.parentPhone) == _normalizedPhone).map((s) => s.name).join('، ')}' : ''}',
              )
            else ...[
              _pinSection(),
              if (!_isEdit && _isNewParent) ...[
                const SizedBox(height: 12),
                const DialogNote(
                  'ولي أمر جديد: سيُنشأ حسابه مع الطالب، وتظهر كلمة المرور مرة واحدة بعد الحفظ.',
                ),
              ],
            ],
            const SizedBox(height: 22),
            DialogActions(
              children: [
                AppButton(
                  label: 'إلغاء',
                  style: AppButtonStyle.outline,
                  onPressed: _saving ? null : () => Navigator.of(context).pop(),
                ),
                AppButton(
                  label: _saving
                      ? 'جارٍ الحفظ...'
                      : (_isEdit ? 'تحديث التعديلات' : 'حفظ الطالب'),
                  icon: LucideIcons.check,
                  style: AppButtonStyle.amber,
                  onPressed: _saving ? null : _submit,
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }

  /// كلمة المرور إلزامية لولي أمر جديد، واختيارية للمسجّل.
  Widget _pinSection() {
    final isNew = _isNewParent;
    final help = isNew
        ? 'ولي أمر جديد: سلّمه كلمة المرور، فالخادم لا يستطيع عرضها لاحقاً.'
        : 'اترك الحقل فارغاً للإبقاء على كلمة المرور الحالية. تغييرها يُخرج ولي الأمر من كل أجهزته.';

    return _labeled(
      FieldLabel('كلمة مرور ولي الأمر', required: isNew),
      ConstrainedBox(
        constraints: const BoxConstraints(maxWidth: 600),
        child: AppTextField(
          controller: _pin,
          password: true,
          obscure: !_showPin,
          maxLength: 72,
          ltr: true,
          mono: true,
          textAlign: TextAlign.center,
          fontSize: 16,
          fontWeight: FontWeight.bold,
          keyboardType: TextInputType.visiblePassword,
          hint: isNew
              ? '16–72 رمزاً: حرف ورقم ورمز، بلا مسافات'
              : 'فارغ = بدون تغيير',
          onChanged: (_) => setState(() => _pinAutoGenerated = false),
          validator: (v) {
            final t = v ?? '';
            if (t.isEmpty) {
              return isNew ? 'كلمة المرور مطلوبة لولي أمر جديد' : null;
            }
            return isValidParentPin(t)
                ? null
                : 'استخدم 16–72 رمزاً إنجليزياً مع حرف ورقم ورمز، دون مسافات';
          },
          suffix: Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              IconButton(
                tooltip: _showPin ? 'إخفاء' : 'إظهار',
                onPressed: () => setState(() => _showPin = !_showPin),
                icon: Icon(
                  _showPin ? LucideIcons.eyeOff : LucideIcons.eye,
                  size: 16,
                ),
                color: AppColors.textMuted,
              ),
              IconButton(
                tooltip: 'نسخ',
                onPressed: _pin.text.isEmpty ? null : _copyPin,
                icon: const Icon(LucideIcons.copy, size: 16),
                color: AppColors.textMuted,
              ),
              IconButton(
                tooltip: 'توليد كلمة مرور جديدة',
                onPressed: () => setState(() {
                  _pin.text = generateParentPin();
                  _pinAutoGenerated = true;
                  _showPin = false;
                }),
                icon: const Icon(LucideIcons.refreshCw, size: 16),
                color: AppColors.brand,
              ),
            ],
          ),
        ),
      ),
      help: help,
    );
  }

  Widget _errorBanner() => Container(
    margin: const EdgeInsets.only(bottom: 16),
    padding: const EdgeInsets.all(12),
    decoration: BoxDecoration(
      color: AppColors.badBg,
      borderRadius: BorderRadius.circular(AppRadius.control),
    ),
    child: Row(
      children: [
        const Icon(LucideIcons.circleAlert, size: 16, color: AppColors.redDark),
        const SizedBox(width: 8),
        Expanded(
          child: Text(
            _error!,
            style: const TextStyle(
              fontSize: 12,
              fontWeight: FontWeight.bold,
              color: AppColors.redDark,
            ),
          ),
        ),
      ],
    ),
  );

  Widget _twoCols(Widget a, Widget b) {
    return LayoutBuilder(
      builder: (context, c) {
        if (c.maxWidth < 420) {
          return Column(children: [a, const SizedBox(height: 14), b]);
        }
        return Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Expanded(child: a),
            const SizedBox(width: 14),
            Expanded(child: b),
          ],
        );
      },
    );
  }

  Widget _labeled(Widget label, Widget field, {String? help}) => Column(
    crossAxisAlignment: CrossAxisAlignment.stretch,
    children: [
      label,
      const SizedBox(height: 6),
      field,
      if (help != null) ...[
        const SizedBox(height: 4),
        Text(
          help,
          style: const TextStyle(fontSize: 12, color: AppColors.textMuted),
        ),
      ],
    ],
  );
}
